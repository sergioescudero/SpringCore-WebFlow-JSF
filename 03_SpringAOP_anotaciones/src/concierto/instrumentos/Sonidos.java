package concierto.instrumentos;

public class Sonidos {

	private String sonidoTambor;
	private String sonidoGuitarra;
	private String sonidoTrompeta;
	public String getSonidoTambor() {
		return sonidoTambor;
	}
	public void setSonidoTambor(String sonidoTambor) {
		this.sonidoTambor = sonidoTambor;
	}
	public String getSonidoGuitarra() {
		return sonidoGuitarra;
	}
	public void setSonidoGuitarra(String sonidoGuitarra) {
		this.sonidoGuitarra = sonidoGuitarra;
	}
	public String getSonidoTrompeta() {
		return sonidoTrompeta;
	}
	public void setSonidoTrompeta(String sonidoTrompeta) {
		this.sonidoTrompeta = sonidoTrompeta;
	}
}
